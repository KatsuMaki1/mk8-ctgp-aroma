"""Generate tools/native/ww_ct_table.h: native course id (16..63) -> CTGP course directory for the Worldwide roulette.

The 48 Booster CTs sit one-to-one on the 48 native base/retro/DLC slots (booster_pass.TRACKS: first field = native donor directory, second = CT name).
Every CTGP client carries the same table, so in a CTGP room the same roulette result loads the same CT for everyone.
Usage: python ww_ct_table.py [catalog.json]
"""
import ast, json, sys
from pathlib import Path

HERE = Path(__file__).parent
CATALOG = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('E:/claude-code/protarium-mk8-server/config/ctgp-catalog.json')
# Native course ids = indices of the game's course directory table (see docs/WW_CT_VOTE.md).
DONOR_ID = {d: i for i, d in enumerate([
    'Gu_MarioCircuit', 'Gu_DossunIseki', 'Gu_City', 'Gu_Cake', 'Gu_HorrorHouse', 'Gu_Expert', 'Gu_Desert', 'Gu_Cloud', 'Gu_SnowMountain', 'Gu_Techno',
    'Gu_Airport', 'Gu_FirstCircuit', 'Gu_WaterPark', 'Gu_Ocean', 'Gu_BowserCastle', 'Gu_RainbowRoad', 'G3ds_DKJungle', 'Gwii_MooMooMeadows',
    'G64_PeachCircuit', 'G64_KinopioHighway', 'Gds_PukupukuBeach', 'Ggc_SherbetLand', 'Gagb_MarioCircuit', 'G3ds_MusicPark', 'Gwii_GrumbleVolcano',
    'Gsfc_DonutsPlain3', 'Ggc_DryDryDesert', 'G3ds_PackunSlider', 'Gds_TickTockClock', 'G64_YoshiValley', 'Gds_WarioStadium', 'G64_RainbowRoad',
    'Du_Metro', 'Du_MuteCity', 'Du_DragonRoad', 'Du_Hyrule', 'Du_Animal_Summer', 'Du_ExciteBike', 'Du_Woods', 'Du_IcePark', 'Dgc_YoshiCircuit',
    'Dwii_WariosMine', 'Dsfc_RainbowRoad', 'Dagb_RibbonRoad', 'D3ds_NeoBowserCity', 'Dgc_BabyPark', 'Dagb_CheeseLand', 'Du_BigBlue'], start=16)}


def tracks():
    s = (HERE / 'booster_pass.py').read_text(encoding='utf-8')
    i = s.index('TRACKS=['); j = s.index(']\n#', i) + 1
    return ast.literal_eval(s[i + len('TRACKS='):j])


def main():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    by_name = {t['name']: t['directory'] for t in catalog['tracks']}
    table = {}
    for donor, name, _tag in tracks():
        if donor not in DONOR_ID:
            raise SystemExit('unknown donor ' + donor)
        if name not in by_name:
            raise SystemExit('CT not in catalog: ' + name)
        table[DONOR_ID[donor]] = by_name[name]
    if len(table) != 48 or sorted(table) != list(range(16, 64)):
        raise SystemExit('expected 48 distinct donor slots 16..63, got %d' % len(table))
    lines = ['/* GENERATED by tools/ww_ct_table.py - do not edit. native course id -> CTGP course directory (Worldwide roulette). */',
             '#ifndef WW_CT_TABLE_H', '#define WW_CT_TABLE_H',
             '#define WW_CT_FIRST 16u', '#define WW_CT_COUNT 48u',
             'static const char *const ww_ct_dir[WW_CT_COUNT] = {']
    for i in range(16, 64):
        lines.append('  /* %2d */ "%s",' % (i, table[i]))
    lines += ['};', '#endif', '']
    out = HERE / 'native' / 'ww_ct_table.h'
    out.write_text('\n'.join(lines), encoding='utf-8')
    print('wrote', out, len(table), 'entries')
    for i in (37, 52, 55, 56):
        print(i, '->', table[i])


if __name__ == '__main__':
    main()
