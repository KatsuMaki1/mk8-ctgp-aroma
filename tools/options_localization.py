"""Build the Options catalog from installed EUR messages and CLDR country names.

Only complete language directories are offered. No account data is read.
Additional translations can be supplied through the JSON override file.
"""
from pathlib import Path
import argparse, json, re
import vehicle_messages

LANGUAGES = [('ee','en','English'),('ef','fr','Français'),('ed','de','Deutsch'),
             ('es','es','Español'),('ei','it','Italiano'),('ep','pt','Português'),
             ('eg','nl','Nederlands'),('er','ru','Русский')]
UI = {
 'en':['Country','Automatic','Language','Speedometer','ON','OFF'],
 'fr':['Pays','Automatique','Langue','Compteur de vitesse','OUI','NON'],
 'de':['Land','Automatisch','Sprache','Tacho','AN','AUS'],
 'es':['País','Automático','Idioma','Velocímetro','SÍ','NO'],
 'it':['Paese','Automatico','Lingua','Tachimetro','SÌ','NO'],
 'pt':['País','Automático','Idioma','Velocímetro','SIM','NÃO'],
 'nl':['Land','Automatisch','Taal','Snelheidsmeter','AAN','UIT'],
 'ru':['Страна','Автоматически','Язык','Спидометр','ВКЛ','ВЫКЛ'],
}

# Real system IDs that the Cemu/older system country.txt does not list (the real console has them): ID -> ISO.
EXTRA_COUNTRIES = {175: 'SY', 219: 'MA'}

def build(content, country_file, output, overrides=None):
 from babel import Locale
 content, output = Path(content), Path(output)
 custom=json.loads(Path(overrides).read_text(encoding='utf-8')) if overrides else {}
 langs=custom.get('languages',LANGUAGES)
 countries=[(i,m.group(1)) for i,line in enumerate(Path(country_file).read_text().splitlines())
            if (m:=re.fullmatch(r'"([A-Z]{2})",?',line.strip()))]
 for extra_id,extra_iso in EXTRA_COUNTRIES.items():
  if extra_id not in [c[0] for c in countries]:countries.append((extra_id,extra_iso))
 # Preserve the existing first twelve choices; append every other valid system ID.
 first=[77,67,78,110,83,105,94,49,18,1,65,16]
 countries.sort(key=lambda c:(first.index(c[0]) if c[0] in first else len(first)+c[0]))
 lines=['/* Generated by options_localization.py; UTF-16, no runtime allocation. */']
 def string(s):
  raw=s.encode('utf-16-be')+b'\0\0'
  return '(const u16[]){'+','.join(str(int.from_bytes(raw[i:i+2],'big')) for i in range(0,len(raw),2))+'}'
 catalogs=[]
 for code,locale,name in langs:
  merged={}
  for filename in ['Common.msbt','Menu.msbt','Race.msbt','DLC.msbt']:
   path=content/'ui'/code/filename
   if not path.exists():raise ValueError(f'Incomplete language: {path}')
   ids,texts=vehicle_messages.unpack(path.read_bytes())
   for ident,index in ids.items():
    text=texts[index]
    if ident in merged and merged[ident]!=text:raise ValueError('Conflicting message ID')
    merged[ident]=text
  rows=[]
  for ident,raw in sorted(merged.items()):
   if len(raw)%2:raise ValueError('Unaligned UTF-16 message')
   rows.append('{'+str(ident)+',(const u16[]){'+','.join(str(int.from_bytes(raw[i:i+2],'big')) for i in range(0,len(raw),2))+'}}')
  lines.append(f'static const struct LocalMessage messages_{code}[]={{'+','.join(rows)+'};')
  labels=custom.get('ui',{}).get(locale,UI.get(locale))
  if not labels or len(labels)!=6:raise ValueError(f'Missing six Options translations for {locale}')
  loc=Locale.parse(locale)
  historical={'en':'Netherlands Antilles','fr':'Antilles néerlandaises','de':'Niederländische Antillen',
              'es':'Antillas Neerlandesas','it':'Antille Olandesi','pt':'Antilhas Neerlandesas',
              'nl':'Nederlandse Antillen','ru':'Нидерландские Антильские острова'}
  names=[labels[1]]+[custom.get('countries',{}).get(locale,{}).get(iso,str(loc.territories.get(iso,historical.get(locale,iso) if iso=='AN' else iso))) for _,iso in countries]
  lines.append(f'static const u16 *const countries_{code}[]={{'+','.join(map(string,names))+'};')
  catalogs.append('{"'+code+'",'+string(name)+','+','.join(map(string,labels))+f',countries_{code},messages_{code},'+str(len(merged))+'}')
 lines.append('static const u32 country_ids[]={0,'+','.join(str(i) for i,_ in countries)+'};')
 lines.append('static const struct LocalLanguage languages[]={'+','.join(catalogs)+'};')
 output.mkdir(parents=True,exist_ok=True)
 (output/'options_catalog.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
 report={'languages':[x[0] for x in langs],'countries':[{'id':i,'iso':s} for i,s in countries],
         'notes':'Valid system IDs; flag textures and online country propagation are separate concerns.'}
 (output/'catalog.json').write_text(json.dumps(report,indent=2)+'\n')
 return report

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('content');p.add_argument('country_file');p.add_argument('output');p.add_argument('--overrides')
 a=p.parse_args();print(build(a.content,a.country_file,a.output,a.overrides))
